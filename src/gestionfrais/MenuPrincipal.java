    private void btneleve4MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btneleve4MouseClicked
        // TODO add your handling code here:
        int confirmation = JOptionPane.showConfirmDialog(
                null,
                "Voulez-vous vraiment vous déconnecter ?",
                "Confirmation de déconnexion",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
            );
        if (confirmation == JOptionPane.YES_OPTION) {
            MenuPrincipal.super.dispose();
            LoginApplication cl = new LoginApplication();
            cl.setVisible(true);
        }else {
                // Si l'utilisateur annule la suppression
            JOptionPane.showMessageDialog(null, "Déconnexion annulée.", null, JOptionPane.ERROR_MESSAGE);
            }
        
    }//GEN-LAST:event_btneleve4MouseClicked

