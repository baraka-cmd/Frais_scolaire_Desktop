    public void Selecttb_admin()
     {
         // Récupère le modèle de la JTable, qui gère les données affichées
        DefaultTableModel model = (DefaultTableModel) tb_admin.getModel();

        // Vide le contenu actuel de la table pour repartir à zéro
        model.setRowCount(0);

        try {
            // Connexion à la base de données MySQL 'gestion_des_eleve' avec utilisateur 'root' sans mot de passe
            con = DriverManager.getConnection("jdbc:mysql://localhost/frais_scolaire", "root", "");

            // Requête SQL simple pour récupérer toutes les données de la table 'gestion_eleve'
            String sql = "SELECT * FROM admin_login";

            // Préparation de la requête (permet aussi de sécuriser les paramètres)
            PreparedStatement ps = con.prepareStatement(sql);

            // Exécution de la requête et récupération du résultat
            Rs = ps.executeQuery();

            // Parcours de toutes les lignes récupérées
            while (Rs.next()) {
                // Création d'un tableau d'objets représentant une ligne de la table
                Object[] row = {
                    Rs.getString("matricule"),          // Code élève
                    Rs.getString("fonction"),     // Matricule élève
                    Rs.getString("nom"),      // Bulletin élève
                    Rs.getString("password"),// Année scolaire
                    
                };
                // Ajoute la ligne dans le modèle de la JTable (ajoute donc une ligne visible)
                model.addRow(row);
            }

        } catch (SQLException ex) {
            // En cas d'erreur SQL, affiche la trace dans la console pour le débogage
            ex.printStackTrace();
        
    }
        
        // Événement : lorsqu’une ligne du tableau est sélectionnée avec la souris
    tb_admin.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseReleased(java.awt.event.MouseEvent evt) {
            int selectionner = tb_admin.getSelectedRow();  // Récupère la ligne sélectionnée

            if (selectionner >= 0) {
                DefaultTableModel model = (DefaultTableModel) tb_admin.getModel();

                // Remplir les champs du formulaire avec les valeurs de la ligne sélectionnée
                utilisateur_id.setText(getSafeValue(model, selectionner, 0));
                comborole.setSelectedItem(getSafeValue(model, selectionner, 1));
                nom_utilisateur.setText(getSafeValue(model, selectionner, 2));
                password.setText(getSafeValue(model, selectionner, 3));
                
            
            }
        }

        // Méthode utilitaire pour éviter les erreurs null
        private String getSafeValue(DefaultTableModel model, int row, int col) {
            Object value = model.getValueAt(row, col);
            return value != null ? value.toString() : "";  // Retourne la valeur ou une chaîne vide
        }
});
        
  }  

