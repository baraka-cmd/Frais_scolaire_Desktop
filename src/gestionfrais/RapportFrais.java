    private void exportePDFfraisMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_exportePDFfraisMouseClicked
        // TODO add your handling code here:
  
    
   
        
        // --- 0. Initialisation des données locales (Adapter au besoin) ---
        String anneeScolaireSelectionnee;
        try {
            // CORRECTION : Utilisation de 'anneeScolaire' au lieu de 'anneeScolaireFiltre'
            anneeScolaireSelectionnee = anneeScolaire.getSelectedItem().toString();
        } catch (Exception e) {
            anneeScolaireSelectionnee = "Toutes les années";
        }

        // 1. Vérification des données
        DefaultTableModel model = (DefaultTableModel) tb_rapport_frais.getModel();
        // CORRECTION : Utilisation de 'this' au lieu de 'thisComponent'
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Le rapport est vide. Générez d'abord les données.", "Erreur d'exportation", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Formatage des dates pour l'affichage dans le PDF
        SimpleDateFormat displaySdf = new SimpleDateFormat("dd/MM/yyyy");
        String dateDebutDisplay = (dateDebutFiltre.getDate() == null) ? "Non spécifiée" : displaySdf.format(dateDebutFiltre.getDate());
        String dateFinDisplay = (dateFinFiltre.getDate() == null) ? "Non spécifiée" : displaySdf.format(dateFinFiltre.getDate());

        // 2. Sélection du fichier de destination (Création de fileToSave)
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Sauvegarder le Rapport en PDF");
        fileChooser.setFileFilter(new FileNameExtensionFilter("Fichier PDF (*.pdf)", "pdf"));

        // Utilisation de l'année scolaire dans le nom du fichier
        String defaultFileName = "Rapport_Frais_" + anneeScolaireSelectionnee.replace("/", "-") + "_" + new SimpleDateFormat("yyyyMMdd").format(new Date()) + ".pdf"; 
        fileChooser.setSelectedFile(new File(defaultFileName));
        
        // CORRECTION : Utilisation de 'this' au lieu de 'thisComponent'
        int userSelection = fileChooser.showSaveDialog(this);
        
        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File fileToSave = fileChooser.getSelectedFile();
            
            if (!fileToSave.getAbsolutePath().toLowerCase().endsWith(".pdf")) {
                fileToSave = new File(fileToSave.getAbsolutePath() + ".pdf");
            }
            
            // 3. Logique de génération du PDF
            Document document = new Document(PageSize.A4.rotate()); // Format Paysage
            
            try (FileOutputStream fileOut = new FileOutputStream(fileToSave)) {
                PdfWriter.getInstance(document, fileOut);
                document.open();

                // Polices et styles
                com.itextpdf.text.Font fontTitre = new com.itextpdf.text.Font(com.itextpdf.text.Font.FontFamily.HELVETICA, 18, com.itextpdf.text.Font.BOLD, com.itextpdf.text.BaseColor.BLUE);
                com.itextpdf.text.Font fontInfo = new com.itextpdf.text.Font(com.itextpdf.text.Font.FontFamily.HELVETICA, 10);
                com.itextpdf.text.Font fontHeaderTable = new com.itextpdf.text.Font(com.itextpdf.text.Font.FontFamily.HELVETICA, 9, com.itextpdf.text.Font.BOLD);
                com.itextpdf.text.Font fontData = new com.itextpdf.text.Font(com.itextpdf.text.Font.FontFamily.HELVETICA, 8);


                // --- Titre du Document (Expliquant l'année) ---
                Paragraph title = new Paragraph("RAPPORT DÉTAILLÉ DES ENCAISSEMENTS DES FRAIS SCOLAIRES\nAnnée Académique: " + anneeScolaireSelectionnee, fontTitre);
                title.setAlignment(Element.ALIGN_CENTER);
                title.setSpacingAfter(10);
                document.add(title);
                
                // --- Infos de Filtration (Header Explicatif) ---
                String infoFiltres = String.format(
                    "Ce rapport filtre les données d'encaissement selon les critères suivants : Classe: %s | Sexe: %s | Période d'Encaissement: Du %s au %s",
                    filtreClasseFrais.getSelectedItem().toString(), 
                    filtreSexeFrais.getSelectedItem().toString(),
                    dateDebutDisplay, 
                    dateFinDisplay
                );
                Paragraph subtitle = new Paragraph(infoFiltres, fontInfo);
                subtitle.setAlignment(Element.ALIGN_LEFT);
                subtitle.setSpacingAfter(15);
                document.add(subtitle);
                
                // --- Création du Tableau PDF (8 COLONNES) ---
                PdfPTable pdfTable = new PdfPTable(model.getColumnCount());
                pdfTable.setWidthPercentage(100); 
                
                // Définir la largeur des 8 colonnes (ajustez ces valeurs selon votre besoin)
                pdfTable.setWidths(new float[]{10, 10, 15, 15, 8, 8, 14, 12}); 
                
                // a) Ajouter les EN-TÊTES de colonnes
                for (int i = 0; i < model.getColumnCount(); i++) {
                    PdfPCell header = new PdfPCell(new Paragraph(model.getColumnName(i), fontHeaderTable));
                    header.setHorizontalAlignment(Element.ALIGN_CENTER);
                    header.setBackgroundColor(com.itextpdf.text.BaseColor.LIGHT_GRAY);
                    pdfTable.addCell(header);
                }

                // b) Remplir les DONNÉES
                for (int i = 0; i < model.getRowCount(); i++) {
                    for (int j = 0; j < model.getColumnCount(); j++) {
                        // Utilise la méthode toString() pour éviter les NullPointer
                        String cellValue = model.getValueAt(i, j) != null ? model.getValueAt(i, j).toString() : "";
                        PdfPCell dataCell = new PdfPCell(new Paragraph(cellValue, fontData));
                        
                        // Aligner les colonnes numériques (Montant payé = index 6 dans le modèle d'origine)
                        if (j == 6) { 
                            dataCell.setHorizontalAlignment(Element.ALIGN_RIGHT);
                        } else {
                            dataCell.setHorizontalAlignment(Element.ALIGN_LEFT);
                        }
                        pdfTable.addCell(dataCell);
                    }
                }
                
                document.add(pdfTable);
                
                // --- Total Général ---
                Paragraph total = new Paragraph("TOTAL MONTANT PAYÉ DANS CET INTERVALLE: " + totalMontantpaye.getText() + " USD", fontInfo);
                total.setAlignment(Element.ALIGN_RIGHT);
                total.setSpacingBefore(15);
                document.add(total);
                
                document.close();
                
                // CORRECTION : Utilisation de 'this' au lieu de 'thisComponent'
                JOptionPane.showMessageDialog(this, "Exportation PDF réussie dans : " + fileToSave.getAbsolutePath(), "Succès", JOptionPane.INFORMATION_MESSAGE);

            } catch (Exception ex) {
                ex.printStackTrace();
                // CORRECTION : Utilisation de 'this' au lieu de 'thisComponent'
                JOptionPane.showMessageDialog(this, "Erreur lors de la génération du PDF. Assurez-vous d'avoir les dépendances iText et que les composants UI sont correctement initialisés. Erreur: " + ex.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_exportePDFfraisMouseClicked

