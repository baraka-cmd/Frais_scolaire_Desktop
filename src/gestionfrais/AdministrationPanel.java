    private void btnmodifieradmMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnmodifieradmMouseClicked
        // TODO add your handling code here:
        try {
                // Connexion à la base
                con = DriverManager.getConnection("jdbc:mysql://localhost/frais_scolaire", "root", "");

                // Requête SQL pour mettre à jour les données (ajout de la colonne photo)
                String sql = "UPDATE admin_login SET fonction = ?, nom = ?, password = ? WHERE matricule = ?";
                ps = con.prepareStatement(sql);

                // Paramètres
                ps.setString(1, comborole.getSelectedItem().toString());
                ps.setString(2, nom_utilisateur.getText());
                ps.setString(3, password.getText());
                ps.setString(4, utilisateur_id.getText());
                
                
                int rowsUpdated = ps.executeUpdate();  // Exécuter la mise à jour


                if (rowsUpdated > 0) {
                    JOptionPane.showMessageDialog(null, "Données modifiées avec succès !");
                             // Recharge les données dans le tableau
                    afficherTable(); 
                    tb_admin.clearSelection();  // Désélectionner toute ligne
                } else {
                    JOptionPane.showMessageDialog(null, "Matricule inexistant", null, JOptionPane.ERROR_MESSAGE);
                }

            } catch (SQLException ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(null, "Erreur lors de la modification", null, JOptionPane.ERROR_MESSAGE);
            }
        
    }//GEN-LAST:event_btnmodifieradmMouseClicked

