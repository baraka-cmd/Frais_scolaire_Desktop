    private void GenererRapportDetteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GenererRapportDetteActionPerformed
        // TODO add your handling code here:
        
    String filtreClasse = filtreClasseFrais.getSelectedItem().toString();
    String montantMinStr = montantMinSurRapportDette.getText().trim();
    
    DefaultTableModel model = (DefaultTableModel) tb_rapport_dette.getModel();
    model.setRowCount(0); // Vider le tableau
    
    double totalGeneralDette = 0;
    double montantMinimum = 0.0;

    // --- 0. Validation de l'Année Scolaire ---
    String anneeScolaireSelectionnee;
    try {
        anneeScolaireSelectionnee = anneeScolaire.getSelectedItem().toString();
        // Empêcher la génération du rapport pour "Toutes les années" ou si non sélectionné.
        if (anneeScolaireSelectionnee.isEmpty() || anneeScolaireSelectionnee.equalsIgnoreCase("Toutes les années") || anneeScolaireSelectionnee.equalsIgnoreCase("Toutes")) {
             JOptionPane.showMessageDialog(this, "Veuillez sélectionner une année scolaire spécifique pour générer le rapport de dette.", "Attention", JOptionPane.WARNING_MESSAGE);
             return;
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Erreur lors de la récupération de l'année scolaire.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }


    // 1. Validation du Montant Minimum
    if (!montantMinStr.isEmpty()) {
        try {
            montantMinimum = Double.parseDouble(montantMinStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Veuillez entrer un nombre valide pour le Montant Minimum.", "Erreur de Saisie", JOptionPane.ERROR_MESSAGE);
            return;
        }
    }

    try (Connection con = DatabaseManager.getConnection()) { 
        
        StringBuilder sqlBuilder = new StringBuilder();
        
        // --- MISE À JOUR SQL : Ajout de f.annee_scolaire dans SELECT ---
        // La table doit maintenant avoir 8 colonnes de données (plus la colonne "---")
        sqlBuilder.append("SELECT e.matricule, e.nom, e.post_nom, e.classe, e.sexe, f.montant_paye, f.reste_a_payer, f.annee_scolaire ");
        sqlBuilder.append("FROM tb_frais f ");
        sqlBuilder.append("JOIN tb_eleve e ON f.matricule_eleve = e.matricule ");
        
        // Critères de dette: Reste à payer DOIT être >= au Montant Minimum
        sqlBuilder.append("WHERE f.reste_a_payer >= ?");
        
        // --- AJOUT CLÉ : Filtrer par Année Scolaire ---
        sqlBuilder.append(" AND f.annee_scolaire = ?");
        
        // Ajout conditionnel du filtre CLASSE
        if (!filtreClasse.equalsIgnoreCase("Toutes")) {
            sqlBuilder.append(" AND e.classe = ?");
        }

        sqlBuilder.append(" ORDER BY f.reste_a_payer DESC, e.nom ASC"); 

        PreparedStatement ps = con.prepareStatement(sqlBuilder.toString());
        
        int index = 1;
        ps.setDouble(index++, montantMinimum); // Param 1: Montant Minimum

        // --- Paramétrage de l'Année Scolaire ---
        ps.setString(index++, anneeScolaireSelectionnee); // Param 2: Année Scolaire
        
        if (!filtreClasse.equalsIgnoreCase("Toutes")) {
            ps.setString(index++, filtreClasse); // Param 3: Classe
        }

        ResultSet rs = ps.executeQuery();
        
        while (rs.next()) {
            double montantPaye = rs.getDouble("montant_paye");
            double resteAPayer = rs.getDouble("reste_a_payer");
            String annee = rs.getString("annee_scolaire");
            
            // L'ordre des données dans 'row' doit correspondre aux 8 colonnes récupérées
            Object[] row = {
                "---", // Colonne 1: Placeholder
                rs.getString("matricule"), // Colonne 2
                rs.getString("nom") + " " + rs.getString("post_nom"), // Colonne 3
                rs.getString("classe"), // Colonne 4
                rs.getString("sexe"), // Colonne 5
                montantPaye, // Colonne 6
                resteAPayer, // Colonne 7
                annee // Colonne 8: Année Scolaire (Nouveau)
            };
            
            model.addRow(row);
            totalGeneralDette += resteAPayer;
        }

        totalDetteAccumulé.setText(String.format("%.2f", totalGeneralDette)); 

    } catch (SQLException e) {
        e.printStackTrace(); 
        JOptionPane.showMessageDialog(this, "Erreur SQL lors de la génération du rapport : " + e.getMessage(), "Erreur Base de Données", JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Erreur Inconnue : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_GenererRapportDetteActionPerformed

