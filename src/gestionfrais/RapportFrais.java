    private void rechercherRapportFraisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rechercherRapportFraisActionPerformed
        // TODO add your handling code here:
     
        // Supposons que votre champ de recherche s'appelle champRechercheRapportFrais
        String termeRecherche = champRechercheRapportFrais.getText().trim();
        // Récupère et nettoie le terme de recherche (Matricule ou Nom).

        // Récupération de l'année scolaire sélectionnée
        String anneeScolaireSelectionnee;
        try {
            anneeScolaireSelectionnee = anneeScolaire.getSelectedItem().toString();
            // Tente de récupérer l'année scolaire depuis le ComboBox.
            if (anneeScolaireSelectionnee.isEmpty() || anneeScolaireSelectionnee.equals("Toutes les années")) {
                    JOptionPane.showMessageDialog(this, "Veuillez sélectionner une année scolaire spécifique pour la recherche individuelle.", "Attention", JOptionPane.WARNING_MESSAGE);
                    // L'année est requise pour une recherche ciblée.
                    return;
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Impossible de récupérer l'année scolaire. Assurez-vous que le ComboBox est initialisé.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }


        if (termeRecherche.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Veuillez entrer le Matricule ou le Nom de l'élève à rechercher.", "Attention", JOptionPane.WARNING_MESSAGE);
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tb_rapport_frais.getModel();
        model.setRowCount(0); // Vider le tableau
        // Vide le tableau de rapport des frais.

        double totalMontantVerse = 0;
        // Initialise le compteur pour le total des montants versés.

        // Utilisation de try-with-resources pour la connexion SQL.
        try (Connection con = DatabaseManager.getConnection()) {

            // 1. Définition de la requête SQL
            StringBuilder sqlBuilder = new StringBuilder();

            // Sélectionne les colonnes nécessaires de l'historique (h) et de l'élève (e).
            // Inclus h.ANNEE_SCOLAIRE dans la sélection.
            sqlBuilder.append("SELECT h.date_paiement, e.matricule, e.nom, e.post_nom, e.classe, e.sexe, h.montant_verse, h.ANNEE_SCOLAIRE ");
            sqlBuilder.append("FROM tb_historique_paiement h ");
            sqlBuilder.append("JOIN tb_eleve e ON h.matricule_eleve = e.matricule ");
            // Jointure entre l'historique de paiement et la table des élèves.

            // Utilisation de ANNEE_SCOLAIRE pour la clause WHERE
            // Filtre sur l'année scolaire SÉLECTIONNÉE ET recherche par Matricule exact OU Nom partiel OU Post-nom partiel.
            sqlBuilder.append("WHERE h.ANNEE_SCOLAIRE = ? AND (e.matricule = ? OR e.nom LIKE ? OR e.post_nom LIKE ?)");

            // Tri par date pour afficher les paiements chronologiquement.
            sqlBuilder.append(" ORDER BY STR_TO_DATE(h.date_paiement, '%d/%m/%Y') ASC");

            PreparedStatement ps = con.prepareStatement(sqlBuilder.toString());

            // 2. Paramétrage des valeurs
            int paramIndex = 1;
            ps.setString(paramIndex++, anneeScolaireSelectionnee); // Param 1: Année Scolaire (dans h)
            ps.setString(paramIndex++, termeRecherche);          // Param 2: Matricule exact (recherche stricte)
            ps.setString(paramIndex++, "%" + termeRecherche + "%"); // Param 3: Nom partiel (recherche LIKE)
            ps.setString(paramIndex, "%" + termeRecherche + "%");  // Param 4: Post-nom partiel (recherche LIKE)

            // 3. Exécution et Remplissage du Tableau
            ResultSet rs = ps.executeQuery();

            // Vérifie si le ResultSet est vide (si l'élève n'a pas de paiements).
            if (!rs.isBeforeFirst()) { 
                JOptionPane.showMessageDialog(this, "Aucun historique de paiement trouvé pour cet élève dans l'année " + anneeScolaireSelectionnee + ".", "Résultat", JOptionPane.INFORMATION_MESSAGE);
                totalMontantpaye.setText("0.00");
                return;
            }

            while (rs.next()) {
                double montantVerse = rs.getDouble("montant_verse");

                // Remplissage de la ligne (doit correspondre à l'ordre des colonnes du JTable)
                Object[] row = {
                    rs.getString("date_paiement"),
                    rs.getString("matricule"),
                    rs.getString("nom"),
                    rs.getString("post_nom"),
                    rs.getString("classe"),
                    rs.getString("sexe"),
                    montantVerse,
                    rs.getString("ANNEE_SCOLAIRE") // Ajout de l'année scolaire
                };

                model.addRow(row);
                totalMontantVerse += montantVerse; // Cumul du total
            }

            // 4. Affichage du Total Payé
            totalMontantpaye.setText(String.format("%.2f", totalMontantVerse)); 

        } catch (java.sql.SQLSyntaxErrorException e) {
            // Erreur spécifique si un nom de colonne ou de table est incorrect.
            JOptionPane.showMessageDialog(this, "Erreur SQL : Vérifiez le nom exact de la colonne 'ANNEE_SCOLAIRE' dans la table tb_historique_paiement (casse ou nommage). Détail : " + e.getMessage(), "Erreur de Base de Données", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace(); 
        } catch (java.sql.SQLException e) {
            // Autres erreurs SQL.
            e.printStackTrace(); 
            JOptionPane.showMessageDialog(this, "Erreur SQL lors de la recherche : " + e.getMessage(), "Erreur Base de Données", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            // Erreurs générales.
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erreur Inconnue lors de la recherche : " + e.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
        }
// Le bloc finally est implicite car la connexion est gérée par try-with-resources.
    }//GEN-LAST:event_rechercherRapportFraisActionPerformed

