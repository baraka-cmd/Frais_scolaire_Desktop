    private void modifierAdminMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_modifierAdminMouseClicked
        // TODO add your handling code here:
        String oldUser = ancienNomUtilisateur.getText().trim(); // Récupère l'ancien nom d'utilisateur saisi
            String oldPass = String.valueOf(ancienPassword.getPassword()).trim(); // Récupère l'ancien mot de passe saisi
            String newUser = nouveauNomUtilisateur.getText().trim(); // Récupère le nouveau nom d'utilisateur
            String newPass = String.valueOf(nouveauPassword.getPassword()).trim(); // Récupère le nouveau mot de passe
        try  { // Ouverture d'une connexion à la base de données
            con = DriverManager.getConnection("jdbc:mysql://localhost/frais_scolaire", "root", "");
                String checkSql = "SELECT * FROM modifier_admin WHERE nom_admin = ? AND password_admin = ?"; // Requête pour vérifier les anciens identifiants
                PreparedStatement checkStmt = con.prepareStatement(checkSql); // Préparation de la requête sécurisée
                checkStmt.setString(1, oldUser); // Remplit le premier paramètre avec l'ancien nom utilisateur
                checkStmt.setString(2, oldPass); // Remplit le second avec l'ancien mot de passe
                ResultSet rs = checkStmt.executeQuery(); // Exécute la requête et récupère les résultats

                if (rs.next()) { // Si l'utilisateur existe avec les anciens identifiants
                    String updateSql = "UPDATE modifier_admin SET nom_admin = ?, password_admin = ? WHERE nom_admin = ? AND password_admin = ?"; // Requête de mise à jour
                    PreparedStatement updateStmt = con.prepareStatement(updateSql); // Préparation sécurisée
                    updateStmt.setString(1, newUser); // Nouveau nom utilisateur
                    updateStmt.setString(2, newPass); // Nouveau mot de passe
                    updateStmt.setString(3, oldUser); // Condition ancien nom utilisateur
                    updateStmt.setString(4, oldPass); // Condition ancien mot de passe

                    int rowsAffected = updateStmt.executeUpdate(); // Exécute la mise à jour
                    if (rowsAffected > 0) { // Si au moins une ligne modifiée
                        JOptionPane.showMessageDialog(this, "Modification réussie !"); // Message de succès
                       afficherTable();
                    } else {
                        JOptionPane.showMessageDialog(this, "Erreur lors de la modification."); // Message d'erreur en cas d'échec de mise à jour
                    }
                    updateStmt.close(); // Ferme la requête préparée
                } else {
                    JOptionPane.showMessageDialog(this, "Ancien nom d'utilisateur ou mot de passe incorrect."); // Message si identifiants incorrects
                }
                rs.close(); // Ferme le résultat de la requête
                checkStmt.close(); // Ferme la requête préparée
            } catch (Exception ex) {
                ex.printStackTrace(); // Affiche la trace d'erreur dans la console pour débogage
                JOptionPane.showMessageDialog(this, "Erreur de connexion à la base de données."); // Message d'erreur si problème base de données
            }
        
    }//GEN-LAST:event_modifierAdminMouseClicked

