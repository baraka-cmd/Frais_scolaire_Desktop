    private void rechercherRapportEleveMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_rechercherRapportEleveMouseClicked
        // TODO add your handling code here:
                                                            
    String termeRecherche = champRechercheRapportEleve.getText().trim(); 

    if (termeRecherche.isEmpty()) {
        // Si le champ est vide, on peut relancer le rapport général (comme Générer) ou simplement avertir.
        JOptionPane.showMessageDialog(this, "Veuillez entrer un Matricule, un Nom ou un Post-nom à rechercher.", "Attention", JOptionPane.WARNING_MESSAGE);
        return;
    }

    DefaultTableModel model = (DefaultTableModel) tb_rapport_eleve.getModel();
    model.setRowCount(0); // Vider le tableau
    
    // Réinitialiser les synthèses
    effectifTotalEleve.setText("0");
    Garcon.setText("0");
    fille.setText("0");

    try {
        con = DatabaseManager.getConnection();
        
        // Requête pour rechercher l'élève par matricule, nom ou post_nom
        String sql = "SELECT matricule, nom, post_nom, classe, sexe, telephone " +
                     "FROM tb_eleve " +
                     "WHERE matricule LIKE ? OR nom LIKE ? OR post_nom LIKE ?";

        pst = con.prepareStatement(sql);
        // La recherche se fait par '%terme%' pour permettre la recherche partielle
        pst.setString(1, "%" + termeRecherche + "%");
        pst.setString(2, "%" + termeRecherche + "%");
        pst.setString(3, "%" + termeRecherche + "%");

        rs = pst.executeQuery();
        
        int effectifTotal = 0;
        int garcons = 0;
        int filles = 0;
        
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("matricule"),
                rs.getString("nom"),
                rs.getString("post_nom"),
                rs.getString("classe"),
                rs.getString("sexe"),
                rs.getString("telephone")
            });
            
            // Mise à jour de la synthèse (pour les résultats de la recherche)
            effectifTotal++;
            String sexe = rs.getString("sexe");
            if (sexe != null) {
                if (sexe.equalsIgnoreCase("Masculin")) {
                    garcons++;
                } else if (sexe.equalsIgnoreCase("Feminin")) {
                    filles++;
                }
            }
        }
        
        if (effectifTotal == 0) {
            JOptionPane.showMessageDialog(this, "Aucun élève trouvé pour le terme : " + termeRecherche, "Information", JOptionPane.INFORMATION_MESSAGE);
        }

        // Mise à jour des totaux
        effectifTotalEleve.setText(String.valueOf(effectifTotal));
        Garcon.setText(String.valueOf(garcons));
        fille.setText(String.valueOf(filles));

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Erreur SQL lors de la recherche : " + e.getMessage(), "Erreur Base de Données", JOptionPane.ERROR_MESSAGE);
    } finally {
        try {
            if (rs != null) rs.close();
            if (pst != null) pst.close();
            if (con != null) con.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }

        
    }//GEN-LAST:event_rechercherRapportEleveMouseClicked

