            sqlBuilder.append("SELECT h.date_paiement, e.matricule, e.nom, e.post_nom, e.classe, e.sexe, h.montant_verse, h.annee_scolaire ");

            sqlBuilder.append("FROM tb_historique_paiement h ");
            sqlBuilder.append("JOIN tb_eleve e ON h.matricule_eleve = e.matricule ");

            // CLAUSE WHERE initiale pour la période de date (requise par défaut)
            // Utilise STR_TO_DATE pour comparer correctement les dates stockées en String (dd/MM/yyyy) dans MySQL.
            sqlBuilder.append("WHERE STR_TO_DATE(h.date_paiement, '%d/%m/%Y') BETWEEN STR_TO_DATE(?, '%d/%m/%Y') AND STR_TO_DATE(?, '%d/%m/%Y')");


