    private void configurerInterfaceSelonRole() {
        
        switch (roleUtilisateur) {
            case "Enseignant":
                // Ẩ Cacher les éléments financiers et administratifs pour l'enseignant
                // Exemple (remplacez par les noms de vos composants dans NetBeans) :
                // menuFrais.setVisible(false);
                changerPasswordAdmin.setVisible(false);
           
                
                btneleve3.setVisible(false);
                break;
                
            case "Comptable":
                // 💵 Afficher les éléments de frais et de rapports, mais pas l'administration complète
                // Exemple :
                btneleve4.setVisible(false);
                break;
                
            case "Directeur":
                // L'administrateur voit tout.
                break;
                
            default:
                JOptionPane.showMessageDialog(this, "Rôle non reconnu. Déconnexion.", "Erreur", JOptionPane.ERROR_MESSAGE);
                this.dispose(); 
                break;
        }
    }
    
    
    
