    private void btnsupprimeradmMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnsupprimeradmMouseClicked
        // TODO add your handling code here:
        String num = utilisateur_id.getText();

            // Demander confirmation à l'utilisateur avant la suppression
            int confirmation = JOptionPane.showConfirmDialog(
                null,
                "Voulez-vous vraiment supprimer cet utilisateur ?",
                "Confirmation de suppression",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
            );

            // Si l'utilisateur confirme la suppression
            if (confirmation == JOptionPane.YES_OPTION) {
                try (
                    // Connexion à la base de données
                    Connection con = DriverManager.getConnection("jdbc:mysql://localhost/frais_scolaire", "root", "");
                    java.sql.Statement stmt = con.createStatement()
                ) {
                    // Exécution de la requête de suppression
                    stmt.executeUpdate("DELETE FROM admin_login WHERE matricule = '" + num + "'");

                    // Afficher un message de confirmation
                    JOptionPane.showMessageDialog(null, "Utilisateur supprimé avec succès.", "Suppression", JOptionPane.INFORMATION_MESSAGE);

                    // Fermer la fenêtre actuelle et retourner à l'écran principal
                   afficherTable(); 
                   tb_admin.clearSelection();  // Désélectionner toute ligne

                } catch (SQLException ex) {
                    // En cas d'erreur SQL
                    JOptionPane.showMessageDialog(null, "Erreur : " + ex.getMessage(), "Erreur", JOptionPane.ERROR_MESSAGE);
                }

            } else {
                // Si l'utilisateur annule la suppression
                System.out.println("Suppression annulée.");
            }
        
    }//GEN-LAST:event_btnsupprimeradmMouseClicked

